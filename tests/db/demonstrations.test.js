import { afterAll, beforeAll, describe, it, expect } from 'vitest';
import { mkdir, writeFile, readFile } from 'node:fs/promises';
import { freshMysql, freshMongo, mysqlFixtures } from './helpers.js';
import { applyMongoSchemas } from '../../backend/src/repositories/mongoSchemaRepository.js';
import { seedRecruitmentSamples } from '../../backend/src/services/sampleSeedService.js';
import { mysqlDemo } from '../../backend/src/repositories/demoQueryRepository.js';
import {
  upcomingRounds,
  roundTypeDistribution,
  commonDocuments,
} from '../../database/mongodb/queries/pipelines.js';
import { readMigrations } from '../../backend/src/repositories/migrationRepository.js';
let pool, connection;
beforeAll(async () => {
  ({ pool } = await freshMysql());
  await mysqlFixtures(pool);
  await pool.execute(
    "UPDATE placement_drives SET status = 'published' WHERE id = 1",
  );
  connection = await freshMongo();
  await applyMongoSchemas(connection);
  await seedRecruitmentSamples(pool, connection, 1, 1);
  await pool.execute(
    "INSERT INTO student_applications (id, drive_id, student_id, status) VALUES (1, 1, 1, 'selected')",
  );
  await pool.execute(
    "INSERT INTO application_status_history (application_id, to_status, changed_by) VALUES (1, 'selected', 1)",
  );
});
afterAll(async () => {
  if (pool) await pool.end();
  if (connection) await connection.close();
});
describe('Executable DBMS demonstrations', () => {
  it('keeps schema.sql identical to the ordered migration snapshot after checkout newline normalization', async () => {
    const migrations = await readMigrations();
    const header =
      '-- Reference snapshot generated by backend/scripts/schemaSnapshot.js from ordered migrations.\n-- Apply with db:migrate, not this reference file; schema_migrations is runner-owned metadata.\n\n';
    expect(
      (
        await readFile(
          new URL('../../database/mysql/schema.sql', import.meta.url),
          'utf8',
        )
      ).replace(/\r\n/g, '\n'),
    ).toBe(
      header +
        migrations
          .map((migration) => migration.sql.replace(/\r\n/g, '\n'))
          .join('\n'),
    );
  });
  it('runs join, subquery, pagination and aggregate examples and records real EXPLAIN plans', async () => {
    const cases = [
      [
        'published_drives',
        ['published', '2030-01-01', 10, 0],
        'idx_drives_status_deadline',
      ],
      [
        'student_applications',
        [1, 'selected'],
        'idx_applications_student_status',
      ],
      ['drive_applications', [1, 'selected'], 'idx_applications_drive_status'],
      ['company_postings', [1], 'idx_job_postings_company'],
      ['branch_cohort', [1, 2030], 'idx_students_branch_year'],
      ['application_history', [1], 'idx_history_application_changed'],
      ['eligible_students', [1]],
      ['company_selections', []],
    ];
    const evidence = [];
    for (const [name, parameters, expectedIndex] of cases) {
      const result = await mysqlDemo(pool, name, parameters);
      expect(result.rows).toHaveLength(1);
      if (expectedIndex)
        expect(
          result.plan.some(
            (row) =>
              row.possible_keys?.split(',').includes(expectedIndex) ||
              row.key === expectedIndex,
          ),
        ).toBe(true);
      if (name === 'eligible_students')
        expect(result.rows[0].student_id).toBe(1);
      if (name === 'company_selections')
        expect(result.rows[0].selected_count).toBe(1);
      evidence.push({
        name,
        rowsReturned: result.rows.length,
        plan: result.plan,
      });
    }
    const output = new URL('../../test-results/', import.meta.url);
    await mkdir(output, { recursive: true });
    await writeFile(
      new URL('database-explain.json', output),
      JSON.stringify(evidence, null, 2),
    );
  });
  it('runs actual Mongo aggregation and projection queries', async () => {
    const collection = connection.db.collection('recruitment_processes');
    const upcoming = await collection
      .aggregate(upcomingRounds([1], new Date('2030-01-01')))
      .toArray();
    expect(upcoming).toHaveLength(1);
    expect(upcoming[0].roundName).toBe('Aptitude assessment');
    const distribution = await collection
      .aggregate(roundTypeDistribution())
      .toArray();
    expect(distribution).toEqual([
      { _id: 'assessment', count: 1 },
      { _id: 'interview', count: 1 },
    ]);
    expect(
      await collection.aggregate(commonDocuments()).toArray(),
    ).toHaveLength(2);
    const checklist = await collection.findOne(
      { placementDriveId: 1 },
      { projection: { _id: 0, requiredDocuments: 1 } },
    );
    expect(Object.keys(checklist)).toEqual(['requiredDocuments']);
  });
});
